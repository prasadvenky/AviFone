#!/usr/bin/env python3
"""Copy a small, fixed sample of Svarah (Indian-English benchmark, CC-BY-4.0) into the
instrumented test assets, so WerTest measures the Android pipeline on Indian English.

    python tools/make_svarah_subset.py --svarah ~/datasets/Svarah --count 20

Reads svarah_manifest.json (one JSON object per line: audio_filepath, duration, text), picks
`count` clips between 3 and 10 s with a fixed seed, writes them as 16 kHz mono 16-bit WAV to
app/src/androidTest/assets/wer/svarah/, and appends them to wer/manifest.tsv. Re-running
replaces the previous subset.
"""
import argparse
import json
import os
import random

import numpy as np
import soundfile as sf

HERE = os.path.dirname(os.path.abspath(__file__))
ASSETS = os.path.join(HERE, "..", "app", "src", "androidTest", "assets")
MARK = "# --- svarah subset (generated by tools/make_svarah_subset.py) ---"


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--svarah", required=True, help="folder holding svarah_manifest.json and audio/")
    ap.add_argument("--count", type=int, default=20)
    ap.add_argument("--seed", type=int, default=7)
    args = ap.parse_args()

    manifest = os.path.join(args.svarah, "svarah_manifest.json")
    items = [json.loads(l) for l in open(manifest, encoding="utf-8") if l.strip()]
    items = [i for i in items if 3.0 <= float(i.get("duration", 0)) <= 10.0 and i.get("text", "").strip()]
    random.Random(args.seed).shuffle(items)
    chosen = items[:args.count]

    out_dir = os.path.join(ASSETS, "wer", "svarah")
    os.makedirs(out_dir, exist_ok=True)
    for f in os.listdir(out_dir):
        os.remove(os.path.join(out_dir, f))

    lines = []
    for n, item in enumerate(chosen, 1):
        src = item["audio_filepath"]
        if not os.path.isabs(src):
            src = os.path.join(args.svarah, src)
        audio, rate = sf.read(src, dtype="float32", always_2d=True)
        audio = audio.mean(axis=1)
        if rate != 16000:
            m = int(round(len(audio) * 16000 / rate))
            audio = np.interp(np.linspace(0, len(audio) - 1, m), np.arange(len(audio)), audio).astype(np.float32)
        name = f"svarah_{n:02d}.wav"
        sf.write(os.path.join(out_dir, name), audio, 16000, subtype="PCM_16")
        text = " ".join(item["text"].split())
        lines.append(f"wer/svarah/{name}\t\t\t{text}")

    tsv = os.path.join(ASSETS, "wer", "manifest.tsv")
    existing = open(tsv, encoding="utf-8").read().split("\n") if os.path.exists(tsv) else []
    if MARK in existing:
        existing = existing[:existing.index(MARK)]
    while existing and not existing[-1].strip():
        existing.pop()
    with open(tsv, "w", encoding="utf-8") as f:
        f.write("\n".join(existing + [MARK] + lines) + "\n")
    total = sum(float(i["duration"]) for i in chosen)
    print(f"wrote {len(chosen)} clips ({total:.0f} s) to {out_dir} and appended them to {tsv}")
    print("Attribution: Svarah, AI4Bharat (https://github.com/AI4Bharat/Svarah), CC-BY-4.0.")


if __name__ == "__main__":
    main()
